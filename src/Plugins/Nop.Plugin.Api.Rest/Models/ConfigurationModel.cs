using System.ComponentModel.DataAnnotations;
using Nop.Web.Framework.Models;
using Nop.Web.Framework.Mvc;
using Nop.Web.Framework.Mvc.ModelBinding;

namespace Nop.Plugin.Api.Rest.Models;

public record ConfigurationModel : BaseNopModel
{
    [NopResourceDisplayName("Plugin.Api.Rest.SwaggerUi")]
    public string SwaggerUiUrl { get; set; }

    [NopResourceDisplayName("Plugin.Api.Rest.SwaggerJson")]
    public string SwaggerJsonUrl { get; set; }

    /// <summary>
    /// Gets or sets the identifier of the store the settings are being edited for, 0 for all stores
    /// </summary>
    public int ActiveStoreScopeConfiguration { get; set; }

    [NopResourceDisplayName("Plugin.Api.Rest.ApiKey")]
    [NoTrim]
    public string ApiKey { get; set; }
    public bool ApiKey_OverrideForStore { get; set; }

    [NopResourceDisplayName("Plugin.Api.Rest.RateLimitPerMinute")]
    [Range(1, int.MaxValue)]
    public int RateLimitPerMinute { get; set; }
    public bool RateLimitPerMinute_OverrideForStore { get; set; }

    [NopResourceDisplayName("Plugin.Api.Rest.RequireApiKeyForReads")]
    public bool RequireApiKeyForReads { get; set; }
    public bool RequireApiKeyForReads_OverrideForStore { get; set; }

    /// <summary>
    /// Gets or sets the key generated by the generate action, so it can be shown once before saving
    /// </summary>
    public string GeneratedApiKey { get; set; }
}